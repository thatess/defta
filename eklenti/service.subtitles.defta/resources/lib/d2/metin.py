_YAZI = {}
for _kimlik, _ad, _yazi in TABLO:
    globals()[_ad] = _kimlik
    _YAZI[_kimlik] = _yazi

_cevirici = None


def kur(cevirici):
    """Kodi'nin dil dosyası okuyucusu (Addon.getLocalizedString). Kurulmazsa tablodaki yazı kullanılır (testler)."""
    global _cevirici
    _cevirici = cevirici


def al(kimlik, **alanlar):
    yazi = (_cevirici(kimlik) if _cevirici else "") or _YAZI.get(kimlik, str(kimlik))
    return yazi.format(**alanlar) if alanlar else yazi


def po_metni():
    """strings.po içeriği (paketleme sırasında yazılır)."""
    satirlar = ['# Defta — arayüz yazıları (resources/lib/d2/metin.py dosyasından üretildi; burada düzenlemeyin)',
                'msgid ""', 'msgstr ""', '"Content-Type: text/plain; charset=UTF-8\\n"',
                '"Language: en_GB\\n"', ""]
    for kimlik, _, yazi in TABLO:
        satirlar += [f'msgctxt "#{kimlik}"', 'msgid "' + yazi.replace("\\", "\\\\").replace('"', '\\"') + '"',
                     'msgstr ""', ""]
    return "\n".join(satirlar)
